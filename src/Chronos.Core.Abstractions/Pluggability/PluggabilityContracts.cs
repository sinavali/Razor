/// <summary>Calculates custom performance metrics.</summary>
public interface IMetricsProvider
{
    /// <summary>Calculates a dictionary of custom metrics.</summary>
    IReadOnlyDictionary<string, double> Calculate(object result, double initialBalance);
}

/// <summary>Engine capability manifest.</summary>
public sealed record EngineCapabilityManifest
{
    /// <summary>Engine version.</summary>
    public required string EngineVersion { get; init; }
    /// <summary>Kernel version.</summary>
    public required string KernelVersion { get; init; }
    /// <summary>Abstractions version.</summary>
    public required string AbstractionsVersion { get; init; }
    /// <summary>Runtime version.</summary>
    public required string RuntimeVersion { get; init; }
    /// <summary>Operating System.</summary>
    public required string OS { get; init; }
    /// <summary>Available capabilities.</summary>
    public required IReadOnlyList<CapabilityDescriptor> Capabilities { get; init; }
    /// <summary>Currently loaded plugins.</summary>
    public required IReadOnlyList<LoadedPlugin> LoadedPlugins { get; init; }
    /// <summary>Boot timestamp.</summary>
    public required DateTime BootTime { get; init; }
}

/// <summary>A specific engine capability.</summary>
public sealed record CapabilityDescriptor
{
    /// <summary>Name of capability.</summary>
    public required string Name { get; init; }
    /// <summary>Version of capability.</summary>
    public required string Version { get; init; }
    /// <summary>Enabled state.</summary>
    public required bool IsEnabled { get; init; }
    /// <summary>Flags configuration.</summary>
    public IReadOnlyList<string> Flags { get; init; } = [];
}

/// <summary>A loaded plugin state.</summary>
public sealed record LoadedPlugin
{
    /// <summary>Plugin Id.</summary>
    public required string PluginId { get; init; }
    /// <summary>Plugin Version.</summary>
    public required string Version { get; init; }
    /// <summary>Type of the plugin.</summary>
    public required string PluginType { get; init; }
    /// <summary>SDK target version.</summary>
    public required string SdkVersion { get; init; }
    /// <summary>Is plugin valid.</summary>
    public required bool IsValid { get; init; }
    /// <summary>Validation error reason if invalid.</summary>
    public string? ValidationError { get; init; }
}

/// <summary>Marks an interface or class with a specific capability version requirement.</summary>
[AttributeUsage(AttributeTargets.Interface | AttributeTargets.Class, AllowMultiple = true)]
public sealed class ChronosFeatureAttribute : Attribute
{
    /// <summary>Name of the feature.</summary>
    public string FeatureName { get; }
    /// <summary>Minimum version required.</summary>
    public string MinVersion { get; }

    /// <summary>Initializes a new instance.</summary>
    public ChronosFeatureAttribute(string featureName, string minVersion = "1.0.0")
    {
        FeatureName = featureName;
        MinVersion = minVersion;
    }
}
